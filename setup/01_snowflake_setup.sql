-- Role for dbt
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS LC_TRANSFORMER;
GRANT ROLE LC_TRANSFORMER TO ROLE SYSADMIN;

-- Warehouse and database
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS LC_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS LENDING_CLUB;
CREATE SCHEMA IF NOT EXISTS LENDING_CLUB.RAW;

-- What dbt may use and read
GRANT USAGE ON WAREHOUSE LC_WH TO ROLE LC_TRANSFORMER;
GRANT USAGE, CREATE SCHEMA ON DATABASE LENDING_CLUB TO ROLE LC_TRANSFORMER;
GRANT USAGE ON SCHEMA LENDING_CLUB.RAW TO ROLE LC_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA LENDING_CLUB.RAW TO ROLE LC_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA LENDING_CLUB.RAW TO ROLE LC_TRANSFORMER;

-- Service user for dbt
USE ROLE USERADMIN;
CREATE USER IF NOT EXISTS DBT_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = LC_TRANSFORMER
  DEFAULT_WAREHOUSE = LC_WH
  RSA_PUBLIC_KEY = '<PASTE_PUBLIC_KEY>';

USE ROLE SECURITYADMIN;
GRANT ROLE LC_TRANSFORMER TO USER DBT_SVC;
GRANT ROLE LC_TRANSFORMER TO USER <YOUR_LOGIN_NAME>;



USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS LC_LOADER;
GRANT ROLE LC_LOADER TO ROLE SYSADMIN;

USE ROLE SYSADMIN;
GRANT USAGE ON WAREHOUSE LC_WH TO ROLE LC_LOADER;
GRANT USAGE ON DATABASE LENDING_CLUB TO ROLE LC_LOADER;
GRANT USAGE ON SCHEMA LENDING_CLUB.RAW TO ROLE LC_LOADER;
GRANT READ, WRITE ON STAGE LENDING_CLUB.RAW.LC_STAGE TO ROLE LC_LOADER;
GRANT USAGE ON FILE FORMAT LENDING_CLUB.RAW.CSV_FF TO ROLE LC_LOADER;
GRANT SELECT, INSERT ON TABLE LENDING_CLUB.RAW.LOANS TO ROLE LC_LOADER;

USE ROLE USERADMIN;
CREATE USER IF NOT EXISTS LOADER_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = LC_LOADER
  DEFAULT_WAREHOUSE = LC_WH
  RSA_PUBLIC_KEY = '<PASTE_PUBLIC_KEY>';

USE ROLE SECURITYADMIN;
GRANT ROLE LC_LOADER TO USER LOADER_SVC;